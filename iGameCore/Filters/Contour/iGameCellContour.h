struct TRIANGLE_CONTOUR {
    int contour[7];
};
static TRIANGLE_CONTOUR triangleCases[] = {
        {{-1, -1, -1}}, {{0, 2, -1}}, {{1, 0, -1}}, {{1, 2, -1}},
        {{2, 1, -1}},   {{0, 1, -1}}, {{2, 0, -1}}, {{-1, -1, -1}},
};
static void Contour(Triangle::Pointer cell, double* cellValues, Points::Pointer points, CellArray::Pointer connectivity,
                    UnsignedIntArray::Pointer types, AttributeSet::Pointer inData, AttributeSet::Pointer outData,
                    igIndex cellId, std::vector<InterpolateEdge>& OriginEdge, std::vector<igIndex>& originCell,
                    bool isMustContour = false) {
    int MASK[3] = {1, 2, 4};
    int i, j, CaseIndex = 0;
    igIndex pId = 0;
    igIndex vhs[IGAME_CELL_MAX_SIZE] = {};
    igIndex vcnt = 0;
    const int* vert = nullptr;
    igIndex vh1 = 0, vh2 = 0;
    Point v1, v2, p;
    double deltaValue = 0.0, t = 0.0;
    for (i = 0; i < 3; i++) {
        if (cellValues[i] >= 0.0) { CaseIndex |= MASK[i]; }
    }
    auto ContourData = (triangleCases + CaseIndex)->contour;
    for (; *ContourData != -1; ContourData += 2) {
        for (i = 0; i < 2; i++) {
            vert = Triangle::edges[ContourData[i]];
            deltaValue = cellValues[vert[1]] - cellValues[vert[0]];
            if (deltaValue > 0) {
                vh1 = vert[0];
                vh2 = vert[1];
            } else {
                vh2 = vert[0];
                vh1 = vert[1];
                deltaValue = -deltaValue;
            }
            t = (deltaValue == 0.0 ? 0.0 : -cellValues[vh1] / deltaValue);

            v1 = cell->GetPoint(vh1);
            v2 = cell->GetPoint(vh2);
            p = v1 + (v2 - v1) * t;
            points->AddPoint(p);
            vhs[i] = points->GetNumberOfPoints() - 1;
            OriginEdge.emplace_back(InterpolateEdge(cell->GetPointId(vh1), cell->GetPointId(vh2), t));
        }
        connectivity->AddCellIds(vhs, 2);
        types->AddValue(IG_LINE);
        originCell.emplace_back(cellId);
    }
}


