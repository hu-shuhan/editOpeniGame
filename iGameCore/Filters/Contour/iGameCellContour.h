struct InterpolateEdge {
    igIndex vh1;
    igIndex vh2;
    double t;

    InterpolateEdge() : vh1(-1), vh2(-1), t(0.0f) {}
    InterpolateEdge(igIndex vh) {
        vh1 = vh;
        vh2 = -1;
        t = 0.0f;
    }
    InterpolateEdge(igIndex _vh1, igIndex _vh2, double _t) {
        vh1 = _vh1;
        vh2 = _vh2;
        t = _t;
    }
};

